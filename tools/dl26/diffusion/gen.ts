// Trains the diffusion chapter's three shipped networks with the page's own Trainer and writes
// src/lib/diffusion-weights.ts. Usage: node tools/dl26/diffusion/gen.ts
import { writeFileSync } from 'node:fs';
import { DiffNet, Trainer, moons } from '../../../src/lib/diffusion-net.ts';
import { Sampler } from '../../../src/lib/diffusion-sample.ts';
import { scatterPNG } from './png.ts';

const b64 = (f: Float32Array) => Buffer.from(f.buffer, f.byteOffset, f.byteLength).toString('base64');
const data = moons(1000);

function train(kind: 'eps' | 'cond' | 'flow', steps: number, snapAt: number[] = []) {
  const net = new DiffNet({ classes: kind === 'cond' ? 2 : 0, seed: 1 });
  const tr = new Trainer(net, data, { objective: kind === 'flow' ? 'flow' : 'eps', steps });
  const snaps: Record<number, string> = {};
  const snap = () => {
    const s = new Sampler(net, { kind: 'ddpm', n: 300, seed: 3 }).runAll();
    snaps[net.steps] = b64(s.last);
  };
  if (snapAt.includes(0)) snap();
  while (!tr.done) {
    tr.step();
    if (snapAt.includes(net.steps)) snap();
  }
  return { net, tr, snaps };
}

const eps = train('eps', 3000, [30, 100, 300, 1000, 3000]);
const cond = train('cond', +(process.env.CSTEPS ?? 4000));
const flow = train('flow', 3000);
const every = 20;
const loss: number[] = [];
for (let i = 0; i < eps.tr.losses.length; i += every) loss.push(+(eps.tr.losses.slice(i, i + every).reduce((a, b) => a + b, 0) / every).toFixed(4));
console.log('params', eps.net.nParams, 'final loss', loss.slice(-3), 'cond', cond.tr.losses.slice(-200).reduce((a,b)=>a+b,0)/200, 'flow', flow.tr.losses.slice(-200).reduce((a,b)=>a+b,0)/200);

const out = `// Generated by training with diffusion-net.ts on moons(1000); see diffusion-models.ts.
// Float32 weights and point clouds, base64-encoded little-endian.

/** Flat weights (W then b per layer) of three networks trained with \`Trainer\` defaults. */
export const WEIGHTS = {
  /** Noise predictor, unconditional, ${eps.net.steps} steps. */
  eps: '${b64(eps.net.save())}',
  /** Noise predictor conditioned on the moon (labels dropped 20% of the time), ${cond.net.steps} steps. */
  cond: '${b64(cond.net.save())}',
  /** Flow-matching velocity predictor, ${flow.net.steps} steps. */
  flow: '${b64(flow.net.save())}',
};

export const STEPS = { eps: ${eps.net.steps}, cond: ${cond.net.steps}, flow: ${flow.net.steps} };

/** The unconditional run's loss, averaged over every ${every} steps. */
export const LOSS_EVERY = ${every};
export const LOSS = [${loss.join(', ')}];

/** 300 DDPM samples (seed 3) from that run's network after this many training steps. */
export const SNAPSHOTS: Record<number, string> = {
${Object.entries(eps.snaps).map(([k, v]) => `  ${k}: '${v}',`).join('\n')}
};
`;
writeFileSync(new URL('../../../src/lib/diffusion-weights.ts', import.meta.url), out);
console.log('bytes', out.length);
for (const w of [0, 1, 3]) {
  const a = new Sampler(cond.net, { kind: 'ddim', steps: 25, n: 400, seed: 3, cls: 0, w }).runAll();
  const b = new Sampler(cond.net, { kind: 'ddim', steps: 25, n: 400, seed: 4, cls: 1, w }).runAll();
  scatterPNG(`guid-w${w}.png`, [{ pts: data.X, rgb: [225, 225, 225] }, { pts: a.last, rgb: [30, 90, 200] }, { pts: b.last, rgb: [220, 120, 30] }]);
}
for (const k of [1, 2, 5]) {
  const a = new Sampler(flow.net, { kind: 'flow', steps: k, n: 400, seed: 3 }).runAll();
  const b = new Sampler(eps.net, { kind: 'ddim', steps: k, n: 400, seed: 3 }).runAll();
  scatterPNG(`few-${k}.png`, [{ pts: data.X, rgb: [225, 225, 225] }, { pts: a.last, rgb: [30, 160, 90] }, { pts: b.last, rgb: [200, 40, 120] }]);
}
for (const [k, v] of Object.entries(eps.snaps)) {
  scatterPNG(`snap-${k}.png`, [{ pts: data.X, rgb: [225, 225, 225] }, { pts: new Float32Array(Buffer.from(v, 'base64').buffer.slice(0)), rgb: [30, 90, 200] }]);
}
